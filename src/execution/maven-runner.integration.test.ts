import { describe, expect, it } from 'vitest';
import { cp, copyFile, mkdtemp, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { createMavenRunner } from './maven-runner.js';

describe('createMavenRunner integration', () => {
  it.skipIf(process.env.FORGE_MAVEN_INTEGRATION !== '1')(
    'executes only the selected JUnit test class',
    async () => {
      // Create a disposable workspace.
      const repo = await mkdtemp(join(tmpdir(), 'forge-maven-test-'));

      const projectPath = 'java-orders';
      const projectDir = join(repo, projectPath);

      const sourceProject = join(process.cwd(), 'examples/java-orders');

      try {
        // Copy only the source code and Maven configuration.
        // Do not copy existing target/ reports.
        await cp(join(sourceProject, 'src'), join(projectDir, 'src'), { recursive: true });

        await copyFile(join(sourceProject, 'pom.xml'), join(projectDir, 'pom.xml'));

        // Use the real command runner, not a mock
        const runner = createMavenRunner(projectPath);

        const result = await runner.run(
          ['java-orders/src/test/java/com/forge/inventory/InventoryServiceTest.java'],
          repo,
        );

        expect(result).toEqual({ exitCode: 0 });

        // Inspect the reports generated by Maven Surefile.
        const reportsDir = join(projectDir, 'target', 'surefire-reports');

        const reports = await readdir(reportsDir);

        expect(reports).toContain('TEST-com.forge.inventory.InventoryServiceTest.xml');
      } finally {
        await rm(repo, { recursive: true, force: true });
      }
    },
    120_000,
  );
});
